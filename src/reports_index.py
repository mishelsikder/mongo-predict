"""Render ``reports/index.html``: one card per report, numbered by API (00 embeddings API, 01 Predictions API).

    uv run python -m src.reports_index

Highlights are computed from the same result files as the reports. Add a card to ``cards()`` when a
report is added.
"""

from __future__ import annotations

import html
import json
import pathlib
import statistics

from src._html import CSS
from src.embeddings_api_report import load, speed_section

HERE = pathlib.Path(__file__).resolve().parents[1] / "reports"  # reports/
DOC = HERE / "index.html"

EXTRA_CSS = """
.lead { max-width:80ch; }
.card { background:var(--surface-1); border:1px solid var(--border);
  border-radius:var(--radius); padding:.8rem 1rem; margin:.8rem 0; }
.card .t { font-weight:650; }
.card .t a { text-decoration:none; }
.card .f { font-family:ui-monospace,Menlo,monospace; font-size:.78rem; color:var(--text-3); margin:.1rem 0 .3rem; }
.card .d, .card .h { color:var(--text-2); font-size:.9rem; max-width:90ch; }
.card .h { margin-top:.3rem; }
"""


def cards():
    stats = speed_section(load("speed_before.json"), load("speed_after.json"))[0]
    d = json.loads((HERE.parent / "results" / "predictions_api.json").read_text())
    ratio = statistics.median(r["t_project"] / r["t_baseline"] for r in d["tasks"])
    conf = d["porto"]["confusion"]
    acc = sum(c["n"] for c in conf if c["actual"] == c["predicted"]) / sum(c["n"] for c in conf)
    return [
        ("00_embeddings_api.html", "00 · embeddings API speed", "src/embeddings_api_report.py",
         "Wrapper speed of the embeddings API (MongoDataset, train_test_split, DocumentFeaturizer) on the 14 MongoDB "
         "sample tasks, in memory and streaming, before and after the performance work.",
         f"the wrapper stages got {stats['sw_med']:.1f}x faster and the end to end fit {stats['st_med']:.1f}x "
         f"faster (median over {stats['n']} task and mode pairs)."),
        ("01_predictions_api.html", "01 · Predictions API: $predict", "src/predictions_api_report.py",
         "A $predict aggregation stage modelled on $vectorSearch: stored prediction models, the stage run on the "
         "client and the rest of the pipeline on the server; overhead and agreement on the 14 sample tasks and a "
         "voyage-4-nano example.",
         f"same predictions as the client-side code on all {len(d['tasks'])} tasks at a median {ratio:.2f}x its time; "
         f"a model trained outside Porto labels Porto's Airbnb listings with accuracy {acc:.3f}."),
    ]


def main() -> None:
    body = []
    for href, title, gen, desc, highlight in cards():
        assert (HERE / href).exists(), f"missing report {href}"
        body.append(
            f'<div class="card"><div class="t"><a href="{href}">{html.escape(title)}</a></div>'
            f'<div class="f">{href} · {gen}</div><div class="d">{html.escape(desc)}</div>'
            f'<div class="h"><b>Highlight:</b> {html.escape(highlight)}</div></div>'
        )
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>mongo-predict reports</title>
<style>{CSS}{EXTRA_CSS}</style></head>
<body>
<h1>mongo-predict: reports</h1>
<p class="lead">Benchmarks of the two APIs of <a href="https://github.com/voyage-ai/mongo-predict">mongo-predict</a>: 00 covers
the embeddings API (<code>pymongopredict.embeddings_api</code>), 01 the predictions API (<code>pymongopredict.predictions_api</code>). Each report
is self-contained; open it for methods, numbers and how to reproduce them.</p>
{''.join(body)}
<footer>Generated by <code>uv run python -m src.reports_index</code>.</footer>
</body></html>
"""
    DOC.write_text(page)
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
